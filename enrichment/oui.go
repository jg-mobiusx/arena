// LookupOUI returns the manufacturer name for the given MAC address.
// Returns empty string if not found.
func LookupOUI(mac string) string {
	// Normalise: uppercase, colon-separated
	mac = strings.ToUpper(strings.TrimSpace(mac))
	mac = strings.ReplaceAll(mac, "-", ":")

	if len(mac) < 8 {
		return ""
	}

	prefix := mac[:8] // "XX:XX:XX"
	if mfr, ok := ouiDB[prefix]; ok {
		return mfr
	}
	return ""
}
